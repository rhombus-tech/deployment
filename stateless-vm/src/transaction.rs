/// Execution context for a transaction
#[derive(Clone, Debug)]
pub struct ExecutionContext {
    /// Current block height
    pub block_height: BlockHeight,
    /// Current state root
    pub state_root: StateRoot,
    /// State bundler for accessing state
    pub state_bundler: Arc<RwLock<StateBundler>>,
}

impl ExecutionContext {
    /// Create a new execution context
    pub fn new(
        block_height: BlockHeight,
        state_root: StateRoot,
        state_bundler: Arc<RwLock<StateBundler>>,
    ) -> Self {
        Self {
            block_height,
            state_root,
            state_bundler,
        }
    }
}

/// Status of a transaction after execution
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TransactionStatus {
    /// Transaction ID
    pub id: TransactionId,
    /// Whether the transaction succeeded
    pub success: bool,
    /// Error message, if any
    pub error: Option<String>,
    /// Gas used by the transaction
    pub gas_used: Gas,
    /// New state root after execution
    pub new_state_root: StateRoot,
    /// Transaction output data
    pub output: Bytes,
    /// Logs generated by the transaction
    pub logs: Vec<Log>,
}

impl TransactionStatus {
    /// Create a new successful transaction status
    pub fn success(
        id: TransactionId,
        gas_used: Gas,
        new_state_root: StateRoot,
        output: Bytes,
        logs: Vec<Log>,
    ) -> Self {
        Self {
            id,
            success: true,
            error: None,
            gas_used,
            new_state_root,
            output,
            logs,
        }
    }
    
    /// Create a new failed transaction status
    pub fn failure(
        id: TransactionId,
        gas_used: Gas,
        error: String,
        state_root: StateRoot,
    ) -> Self {
        Self {
            id,
            success: false,
            error: Some(error),
            gas_used,
            new_state_root: state_root,
            output: Vec::new(),
            logs: Vec::new(),
        }
    }
    
    /// Check if the transaction succeeded
    pub fn is_success(&self) -> bool {
        self.success
    }
    
    /// Get the new state root
    pub fn new_state_root(&self) -> &StateRoot {
        &self.new_state_root
    }
}

