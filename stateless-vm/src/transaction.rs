/// Fallback plan for a failed transaction in a sequence
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FallbackPlan {
    /// Index of the transaction that may fail
    pub tx_index: usize,
    /// Alternate transactions to execute if the main one fails
    pub alternate_transactions: Vec<Transaction>,
    /// Error types that trigger this fallback
    pub error_types: Vec<FallbackErrorType>,
    /// Whether to abort the entire sequence if this fallback is triggered
    pub abort_on_fallback: bool,
}

/// Types of errors that can trigger a fallback
